// Пояснения: всё неочевидное на экране открывает карточку с объяснением и ссылками.
import { h, openSheet } from './ui.js';
import { openUrl } from './actions.js';
import { CANONICAL_HOURS, GREEK_WEEKDAYS } from './scripture.js';
import { HOUR_NAMES, WATCHES, DAY_PARTS } from './sun.js';

export const bible = (az, label) => ({ ru: label, url: `https://azbyka.ru/biblia/?${az}` });
const wiki = (title, label = title.replace(/_/g, ' ')) => ({ ru: `Википедия: ${label}`, url: `https://ru.wikipedia.org/wiki/${title}` });

export function explain({ kicker = 'ἑρμηνεία', title, text = [], links = [] }) {
  openSheet({
    title, kicker,
    render(body) {
      text.forEach((t) => body.append(h('p', { class: 'ex-p' }, t)));
      if (links.length) {
        const list = h('div', { class: 'ex-links' });
        links.forEach((l) => list.append(h('button', { class: 'ex-link', onclick: () => openUrl(l.url, l.ru) },
          h('span', {}, l.ru), h('small', {}, l.url.replace(/^https?:\/\/(www\.)?/, '').split('/')[0]))));
        body.append(list);
      }
    },
  });
}

// маленькая ссылка «что это?» для настроек и подписей
export const infoLink = (entry, label = 'что это?') =>
  h('button', { class: 'info-link', onclick: (e) => { e.stopPropagation(); explain(typeof entry === 'function' ? entry() : entry); } }, label);

